def uesc(s):
    # Unicode-эскейпы разворачиваются javac ДО лексического разбора, поэтому
    # кавычку и обратную косую нельзя подавать как \\uXXXX — они сломают литерал.
    out = []
    for c in s:
        if c == '"':
            out.append('\\"')
        elif c == '\\':
            out.append('\\\\')
        elif ord(c) < 0x20:
            out.append('\\u%04x' % ord(c))
        else:
            out.append('\\u%04x' % ord(c))
    return ''.join(out)

data = []
for ch in ORDER:
    for row in G[ch]:
        bits = 0
        for c in row:
            bits = (bits << 1) | (1 if c == '#' else 0)
        # Сдвиг 0x100: внутри строкового литерала не должно быть управляющих/экранирующих символов
        data.append('\\u%04x' % (0x100 + bits))

# Разбиваем длинную строку на части, чтобы javac не ругался на размер константы
parts = []
cur = ''
for s in data:
    if len(cur) + len(s) > 900:
        parts.append(cur)
        cur = ''
    cur += s
if cur:
    parts.append(cur)

